#!/usr/bin/env python3
"""Generates supabase/commerce-seed.sql (products / zones / slots) from the app's own data.
Run:  python3 scripts/gen-commerce-seed.py"""
import json, re, io
src = open('src/lib/bahbah/data.ts', encoding='utf-8').read()

prods = {}
for p in json.load(open('src/lib/bahbah/real-catalog.json', encoding='utf-8')):
    prods.setdefault(p['id'], float(p['price']))

# featuredProducts block: from "const featuredProducts" to "const mappedRealProducts"
a = src.index('const featuredProducts: Product[] = [')
b = src.index('const mappedRealProducts')
blk = src[a:b]
for m in re.finditer(r'^  \{\n(.*?)^  \},?\n', blk, re.S | re.M):
    body = m.group(1)
    i = re.search(r'^    id: "([^"]+)"', body, re.M)
    pr = re.search(r'^    price: ([0-9.]+)', body, re.M)
    if i and pr:
        prods.setdefault(i.group(1), float(pr.group(1)))

def esc(s): return s.replace("'", "''")
out = ['-- AUTO-GENERATED by scripts/gen-commerce-seed.py — do not edit by hand',
       'insert into public.products (id, price) values']
out.append(',\n'.join(f"  ('{esc(k)}', {v:g})" for k, v in prods.items()))
out.append('on conflict (id) do update set price = excluded.price;\n')

zs = re.search(r'export const deliveryZones: DeliveryZone\[\] = \[(.*?)\n\];', src, re.S).group(1)
rows = []
for m in re.finditer(r'id: "([^"]+)".*?fee: ([0-9.]+),.*?freeOver: ([0-9.]+)', zs, re.S):
    rows.append(f"  ('{m.group(1)}', {m.group(2)}, {m.group(3)})")
out.append('insert into public.delivery_zones (id, fee, free_over) values\n' + ',\n'.join(rows) +
           '\non conflict (id) do update set fee = excluded.fee, free_over = excluded.free_over;\n')

ss = re.search(r'export const deliverySlots: DeliverySlot\[\] = \[(.*?)\n\];', src, re.S).group(1)
rows = []
for blk in re.split(r'\n  \},?', ss):
    i = re.search(r'id: "([^"]+)"', blk)
    if i:
        e = re.search(r'extraFee: ([0-9.]+)', blk)
        rows.append(f"  ('{i.group(1)}', {e.group(1) if e else 0})")
out.append('insert into public.delivery_slots (id, extra_fee) values\n' + ',\n'.join(rows) +
           '\non conflict (id) do update set extra_fee = excluded.extra_fee;\n')
open('supabase/commerce-seed.sql', 'w', encoding='utf-8').write('\n'.join(out))
print(len(prods), 'products;', 'zones/slots ok')
